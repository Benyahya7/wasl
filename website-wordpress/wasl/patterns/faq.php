<h3 class="wp-block-heading has-xl-font-size">What is the pickup code?</h3>
<!-- /wp:heading -->
<!-- wp:paragraph {"style":{"color":{"text":"var(--wp--preset--color--body)"}}} -->
<p class="has-body-color">Every order gets a 4-character code (like K7M2) printed on its label. The driver types it to confirm pickup — no code, no pickup. The code never appears on driver screens before pickup, so the wrong order can't leave your counter.</p>
